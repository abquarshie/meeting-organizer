-- The Meeting Organizer's tables. Every statement is safe to run again: `npm run db:setup` (also run by every
-- Vercel build) and the Python code (db.init_db) both run this file, so a brand-new Neon database fills itself in.
-- prisma/schema.prisma describes the same tables for the TypeScript side; change both together.

CREATE TABLE IF NOT EXISTS students (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    gender TEXT,
    privileges TEXT,
    active INTEGER DEFAULT 1,
    family TEXT,
    groups TEXT,
    suspended INTEGER DEFAULT 0,
    suspended_until TEXT
);

CREATE TABLE IF NOT EXISTS schedules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_date TEXT,
    meeting_type TEXT,
    part_name TEXT,
    assigned_person TEXT,
    part_no INTEGER,
    minutes INTEGER,
    section TEXT,
    role TEXT,
    student_part INTEGER DEFAULT 0,
    needs_assistant INTEGER DEFAULT 0,
    student_id INTEGER,
    assistant_id INTEGER,
    assistant_name TEXT,
    sort_order INTEGER DEFAULT 0,
    hall TEXT DEFAULT 'main_hall'
);

CREATE TABLE IF NOT EXISTS meetings (
    meeting_date TEXT NOT NULL,
    meeting_type TEXT NOT NULL,
    heading TEXT,
    opening_song TEXT,
    middle_song TEXT,
    closing_song TEXT,
    aux INTEGER,
    book TEXT,
    aux_group TEXT,
    PRIMARY KEY (meeting_date, meeting_type)
);

CREATE TABLE IF NOT EXISTS templates (
    name TEXT PRIMARY KEY,
    file_name TEXT,
    data TEXT
);

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts TEXT,
    action TEXT,
    details TEXT
);

CREATE TABLE IF NOT EXISTS workbook_weeks (
    label TEXT PRIMARY KEY,
    position INTEGER,
    data TEXT
);

CREATE TABLE IF NOT EXISTS snapshots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts TEXT,
    reason TEXT,
    meeting_date TEXT,
    meeting_type TEXT,
    data TEXT
);

CREATE TABLE IF NOT EXISTS unavailable (
    student_id INTEGER NOT NULL,
    meeting_date TEXT NOT NULL,
    PRIMARY KEY (student_id, meeting_date)
);

CREATE TABLE IF NOT EXISTS no_meeting_periods (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    note TEXT,
    kind TEXT
);
